import { chromium } from 'playwright-core';
const b = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox'] });
const ctx = await b.newContext({ viewport: { width: 360, height: 780 }, hasTouch: true, isMobile: true });
const p = await ctx.newPage();
p.on('console', m => console.log('C', m.type(), m.text()));
p.on('pageerror', e => console.log('PE', e.message));
await p.goto('http://127.0.0.1:8765/index.html');
await p.waitForSelector('.tab-pill');
await p.locator('.tab-pill', { hasText: 'Dosare' }).tap();
await p.locator('[data-test=fab-add]').tap();
await p.locator('[data-test=editor] [data-k=title]').fill('Țărănescu contra Ștefănescu');
const date = p.locator('[data-test=editor] .date-inp').first();
await date.fill(''); await date.type('15122026');
console.log('date', await date.inputValue());
await p.locator('[data-test=editor] .time-inp').first().type('0930');
await p.locator('[data-test=editor] .stage-pick .st-acte').tap();
await p.screenshot({ path: '/tmp/d1.png' });
await p.locator('[data-test=editor] .m-actions .btn.primary').tap();
await p.waitForTimeout(1000);
await p.screenshot({ path: '/tmp/d2.png' });
console.log(await p.locator('#view').innerText());
await b.close();
